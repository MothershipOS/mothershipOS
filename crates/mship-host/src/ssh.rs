//! The SSH server (OpenSSH, socket-activated on Ubuntu): settings, keys, passwords.

use std::collections::BTreeMap;
use std::os::unix::fs::PermissionsExt;

use mship_core::status::{SshConf, SshStatus};

use crate::util::{Result, fail, load_json, rd, run, run_check, run_input, save_json, truthy};
use crate::wifi;

const CONF: &str = "/etc/mothership/ssh.json";
const DROPIN: &str = "/etc/ssh/sshd_config.d/50-mothership.conf";
/// the phone's address on the USB dev link to a PC
pub const USB_ADDR: &str = "10.42.0.2";
const USERS: &[&str] = &["root", "mship"];

pub fn conf() -> SshConf {
    load_json(CONF)
}

fn write(c: &SshConf) -> Result<()> {
    let mut lines = vec!["# generated by mothershipOS (Settings › SSH); edit through the UI".to_string()];
    if c.listen == "usb" {
        lines.push(format!("ListenAddress {USB_ADDR}"));
    }
    lines.push(format!("PasswordAuthentication {}", if c.password_auth { "yes" } else { "no" }));
    lines.push(format!("PermitRootLogin {}", if c.root_login { "prohibit-password" } else { "no" }));
    std::fs::write(DROPIN, lines.join("\n") + "\n")?;
    run_check("sshd", &["-t"])?;
    save_json(CONF, c)?;
    // Ubuntu runs sshd socket-activated; the generator turns ListenAddress into ssh.socket listeners
    run("systemctl", &["daemon-reload"]);
    if c.enabled {
        run("systemctl", &["enable", "ssh.socket"]);
        run("systemctl", &["restart", "ssh.socket"]);
    } else {
        run("systemctl", &["disable", "--now", "ssh.socket", "ssh.service"]);
    }
    Ok(())
}

fn home(user: &str) -> Option<String> {
    let name = std::ffi::CString::new(user).ok()?;
    let pw = unsafe { libc::getpwnam(name.as_ptr()) };
    if pw.is_null() {
        return None;
    }
    let dir = unsafe { std::ffi::CStr::from_ptr((*pw).pw_dir) };
    Some(dir.to_string_lossy().into_owned())
}

fn uid_gid(user: &str) -> Option<(u32, u32)> {
    let name = std::ffi::CString::new(user).ok()?;
    let pw = unsafe { libc::getpwnam(name.as_ptr()) };
    (!pw.is_null()).then(|| unsafe { ((*pw).pw_uid, (*pw).pw_gid) })
}

/// An authorized_keys line -> its comment (or the start of the key when there is none).
fn key_label(line: &str) -> String {
    let f: Vec<&str> = line.split_whitespace().collect();
    if f.len() > 2 { f[f.len() - 1].to_string() } else { f[0].chars().take(16).collect() }
}

pub fn status() -> SshStatus {
    let c = conf();
    let mut keys = BTreeMap::new();
    for user in USERS {
        let ak = home(user).map(|h| rd(format!("{h}/.ssh/authorized_keys"), "")).unwrap_or_default();
        keys.insert(
            user.to_string(),
            ak.lines().filter(|l| !l.trim().is_empty() && !l.starts_with('#')).map(key_label).collect(),
        );
    }
    let mut pubs: Vec<_> = std::fs::read_dir("/etc/ssh")
        .map(|d| d.flatten().map(|e| e.path()).collect())
        .unwrap_or_else(|_| Vec::new());
    pubs.retain(|p| p.file_name().is_some_and(|n| {
        let n = n.to_string_lossy();
        n.starts_with("ssh_host_") && n.ends_with("_key.pub")
    }));
    pubs.sort();
    let hostkeys = pubs
        .iter()
        .filter_map(|k| {
            let o = run("ssh-keygen", &["-lf", &k.to_string_lossy()]);
            let f: Vec<&str> = o.stdout.split_whitespace().collect();
            (f.len() >= 4).then(|| format!("{} {}", f[f.len() - 1].trim_matches(['(', ')']), f[1]))
        })
        .collect();
    let mut addresses = vec![format!("{USB_ADDR} (USB)")];
    if let Some(ip) = wifi::status().ip.filter(|_| c.listen == "all") {
        addresses.push(format!("{ip} (Wi-Fi)"));
    }
    let active = run("systemctl", &["is-active", "ssh.socket"]).stdout.trim() == "active";
    SshStatus { active, keys, hostkeys, addresses: if c.enabled { addresses } else { vec![] }, conf: c }
}

pub fn set(key: &str, value: &str) -> Result<SshStatus> {
    let mut c = conf();
    match key {
        "listen" if matches!(value, "usb" | "all") => c.listen = value.into(),
        "listen" => return fail("listen must be usb or all"),
        "enabled" => c.enabled = truthy(value),
        "password-auth" => c.password_auth = truthy(value),
        "root-login" => c.root_login = truthy(value),
        _ => return fail(format!("unknown ssh setting {key}")),
    }
    write(&c)?;
    Ok(status())
}

pub fn passwd(user: &str, password: &str) -> Result<()> {
    if !USERS.contains(&user) {
        return fail("user must be mship or root");
    }
    if password.chars().count() < 4 {
        return fail("password too short");
    }
    let o = run_input("chpasswd", &[], Some(&format!("{user}:{password}\n")));
    if !o.ok() {
        return fail(o.message());
    }
    Ok(())
}

/// Is this an OpenSSH public key line?
pub fn valid_key(key: &str) -> bool {
    let re = regex::Regex::new(r"^(ssh-(ed25519|rsa|dss)|ecdsa-sha2-\S+|sk-\S+) [A-Za-z0-9+/=]+( .*)?$").unwrap();
    re.is_match(key)
}

pub fn add_key(user: &str, key: &str) -> Result<SshStatus> {
    if !USERS.contains(&user) {
        return fail("user must be mship or root");
    }
    let key = key.trim();
    if !valid_key(key) {
        return fail("not an OpenSSH public key");
    }
    let (Some(h), Some((uid, gid))) = (home(user), uid_gid(user)) else { return fail(format!("no user {user}")) };
    let d = format!("{h}/.ssh");
    std::fs::create_dir_all(&d)?;
    std::fs::set_permissions(&d, std::fs::Permissions::from_mode(0o700))?;
    let ak = format!("{d}/authorized_keys");
    let mut text = std::fs::read_to_string(&ak).unwrap_or_default();
    text.push_str(key);
    text.push('\n');
    std::fs::write(&ak, text)?;
    for p in [&d, &ak] {
        std::os::unix::fs::chown(p, Some(uid), Some(gid))?;
    }
    std::fs::set_permissions(&ak, std::fs::Permissions::from_mode(0o600))?;
    Ok(status())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keys() {
        assert!(valid_key("ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIGq user@pc"));
        assert!(valid_key("ecdsa-sha2-nistp256 AAAAE2VjZHNh"));
        assert!(!valid_key("ssh-ed25519"));
        assert!(!valid_key("hello world"));
        assert_eq!(key_label("ssh-ed25519 AAAA user@pc"), "user@pc");
        assert_eq!(key_label("ssh-ed25519 AAAAC3NzaC1lZDI1NTE5"), "ssh-ed25519");
    }
}
